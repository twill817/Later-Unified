// Generates src/tokens/tokens.css from src/tokens/tokens.json.
// Run with: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../src/tokens/tokens.json', import.meta.url);
const out = new URL('../src/tokens/tokens.css', import.meta.url);
const t = JSON.parse(readFileSync(src, 'utf8'));

const light = [];
const dark = [];
const add = (name, tok) => {
  const v = tok.value ?? tok.light;
  light.push(`  --lo-${name}: ${v};`);
  if (tok.dark !== undefined && tok.dark !== tok.light) dark.push(`  --lo-${name}: ${tok.dark};`);
};

for (const [k, tok] of Object.entries(t.color)) add(`color-${k}`, tok);
for (const [k, tok] of Object.entries(t.font)) add(`font-${k}`, tok);
for (const [k, tok] of Object.entries(t.space)) add(`space-${k}`, tok);
for (const [k, tok] of Object.entries(t.radius)) add(`radius-${k}`, tok);
for (const [k, tok] of Object.entries(t.shadow)) add(`shadow-${k}`, tok);

const darkBlock = dark.join('\n');
const css = `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */
:root {
${light.join('\n')}
  color-scheme: light;
}

/* Dark: follows the OS unless a light theme is forced */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${darkBlock.replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}

/* Dark: forced */
:root[data-theme="dark"] {
${darkBlock}
  color-scheme: dark;
}
`;

writeFileSync(out, css);
console.log(`Wrote ${light.length} tokens (${dark.length} with dark values) to src/tokens/tokens.css`);
